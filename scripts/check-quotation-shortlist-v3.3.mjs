import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const roster=read('data/roster.v0.1.json');
const sources=read('data/pilot-evidence.v2.1.json');
const registry=read('data/quotation-review.v0.1.json');
const policy=read('data/research/quotation-intake-policy.v3.2.DRAFT.json');
const x=read('data/research/quotation-shortlist.v3.3.DRAFT.json');
assert.equal(roster.characters.length,109);
assert.equal(roster.organizations.length,17);
assert.equal(x.schemaVersion,'v3.3-quotation-shortlist-draft');
assert.equal(x.state,'discussion-shortlist-unverified');
assert.equal(policy.schemaVersion,'v3.2-quotation-intake-policy-draft');
assert.deepEqual(registry.quotationCandidates,[],'legacy published quotes unchanged');
assert.equal(sources.meta.originalCanonScenesVerified,0);
assert.equal(sources.meta.formalEvaluations,0);
assert.equal(x.candidates.length,10);
assert.equal(new Set(x.candidates.map(c=>c.candidateId)).size,10);
assert.deepEqual(x.candidates.map(c=>c.candidateId),Array.from({length:10},(_,i)=>'CQ-'+String(i+1).padStart(3,'0')));
for(const q of x.candidates){
 const person=roster.characters.find(c=>c.id===q.characterId);
 assert.ok(person,'every quote character must exist in canonical roster');
 assert.equal(q.retrievalNameOnly,person.name);
 assert.equal(q.source.sourceType,'domestic-original-language-fan-secondary');
 assert.ok(q.source.url.startsWith('https://'));
 assert.equal(q.source.independentOriginalSceneVerified,false);
 assert.equal(q.original.part,null);
 assert.equal(q.original.episode,null);
 assert.equal(q.original.sceneLocator,null);
 assert.equal(q.original.exactText,null,'no unverified comic dialogue copied');
 assert.equal(q.original.verbatimVerification,'not-checked-by-assistant');
 assert.equal(q.original.verifiedBy,null);
 assert.equal(q.review.userSelected,false);
 assert.equal(q.review.userExactTextConfirmed,false);
 assert.equal(q.review.speakerVerified,false);
 assert.equal(q.review.contextVerified,false);
 assert.equal(q.rights.publishCleared,false);
 assert.equal(q.display.status,'blocked');
 assert.equal(q.display.text,null);
 assert.equal(q.combat.affectsScore,false);
 assert.equal(q.combat.isStatement,false);
}
assert.equal(x.candidates.find(q=>q.candidateId==='CQ-010').kind,'narrative-caption-candidate');
assert.equal(x.candidates.find(q=>q.candidateId==='CQ-010').speakerId,null);
assert.ok(x.candidates.find(q=>q.candidateId==='CQ-009').conflicts.some(c=>c.issue==='alternative transcriptions'));
assert.equal(x.summary.originalVerbatimChecks,0);
assert.equal(x.summary.exactTextStored,0);
assert.equal(x.summary.userApproved,0);
assert.equal(x.summary.approvedForPublicDisplay,0);
assert.equal(x.summary.legacyRegistryChanged,false);
console.log('PASS: 10 unapproved quote motifs, no copied lines, no wrong Character IDs, existing registry/publication/score guards');
