import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const get=p=>JSON.parse(readFileSync(p,'utf8'));
const roster=get('data/roster.v0.1.json');
const pilot=get('data/pilot-evidence.v2.1.json');
const queue=get('data/pilot-review-queue.v2.2.json');
const temporal=get('data/temporal-evaluation-candidates.v0.1.json');
const x=get('data/research/analysis-depth-coverage.v2.9.DRAFT.json');
assert.equal(x.schemaVersion,'v2.9-analysis-depth-coverage-draft');
assert.equal(x.state,'unapproved-methodology-experiment');
assert.equal(roster.characters.length,109);
assert.equal(roster.organizations.length,17);
assert.deepEqual([pilot.battles.length,pilot.evidence.length,pilot.statements.length,queue.records.length],[3,12,7,19]);
const rosterIds=roster.characters.map(c=>c.id);
const rosterSet=new Set(rosterIds),evidenceSet=new Set(pilot.evidence.map(e=>e.id)),statementSet=new Set(pilot.statements.map(s=>s.id));
assert.equal(rosterSet.size,109,'No duplicate Character IDs');
assert.equal(x.coverageIndex.length,109);
assert.deepEqual(x.coverageIndex.map(e=>e.characterId),rosterIds,'All roster entries, stable order');
assert.deepEqual(x.temporalReviewCandidateIds,temporal.candidates.map(c=>c.characterId));
const pilotIds=pilot.battles.map(b=>b.subjectCharacterId);
assert.deepEqual(pilotIds,['char-033','char-087','char-071']);
for(const e of x.coverageIndex){
 assert.ok(rosterSet.has(e.characterId));
 assert.equal(e.l1,'roster-indexed-no-combat-profile');
 assert.equal(e.l2,pilotIds.includes(e.characterId)?'candidate-evidence-linked':'not-started');
 assert.equal(e.l3,e.characterId==='char-033'?'unapproved-hypotheses-exist':'not-started');
 const battleIds=pilot.battles.filter(b=>b.subjectCharacterId===e.characterId).map(b=>b.id);
 assert.deepEqual(e.battleCandidateIds,battleIds);
 assert.deepEqual(e.evidenceCandidateIds,pilot.evidence.filter(z=>battleIds.includes(z.battleId)).map(z=>z.id));
 assert.deepEqual(e.statementCandidateIds,pilot.statements.filter(z=>z.targetCharacterIds.includes(e.characterId)).map(z=>z.id));
 for(const id of e.evidenceCandidateIds)assert.ok(evidenceSet.has(id));
 for(const id of e.statementCandidateIds)assert.ok(statementSet.has(id));
 assert.deepEqual(Object.keys(e).sort(),['characterId','l1','l2','l3','battleCandidateIds','evidenceCandidateIds','statementCandidateIds'].sort());
}
assert.equal(x.pilotL2ReviewPacks.length,3);
for(const p of x.pilotL2ReviewPacks){
 assert.ok(pilotIds.includes(p.characterId));
 assert.equal(p.l2Status,'review-questions-ready-but-not-canon');
 assert.equal(p.l3Status,p.characterId==='char-033'?'tactical-hypothesis-research-only':'not-started');
 assert.equal(p.reviewApproval,'none');
 assert.equal(p.scores,null);
 assert.equal(p.sufficiency,'unassessed');
 assert.ok(p.coreQuestions.length>=3);
 const battles=pilot.battles.filter(b=>b.subjectCharacterId===p.characterId).map(b=>b.id);
 assert.deepEqual(p.battleCandidateIds,battles);
 assert.deepEqual(p.evidenceCandidateIds,pilot.evidence.filter(e=>battles.includes(e.battleId)).map(e=>e.id));
 assert.deepEqual(p.existingReviewRecords,queue.records.filter(e=>battles.includes(e.parentBattleId)).map(e=>e.recordId));
}
assert.deepEqual(x.pilotL2ReviewPacks.map(p=>p.characterId),pilotIds);
assert.deepEqual(x.pilotL2ReviewPacks.map(p=>p.evidenceCandidateIds.length),[4,4,4]);
assert.ok(x.pilotL2ReviewPacks.filter(p=>p.researchRefs.length).every(p=>p.characterId==='char-033'));
assert.deepEqual(Object.keys(x.levelDefinitions),['L1','L2','L3']);
assert.deepEqual(x.specialistStatuses,['used-with-observation','not-used','ability-unknown','not-applicable','unassessed']);
assert.equal(x.genericRecordTemplate.canonFactCandidate.directlyVerified,false);
assert.equal(x.genericRecordTemplate.evaluation.score,null);
assert.equal(x.genericRecordTemplate.evaluation.sufficiency,'unassessed');
assert.equal(x.genericRecordTemplate.evaluation.approval,'none');
assert.equal(x.genericRecordTemplate.calculation.enabled,false);
assert.equal(x.genericRecordTemplate.calculation.result,null);
assert.equal(x.genericRecordTemplate.temporal.splitDecision,'not-decided');
assert.deepEqual(Object.values(x.approval),[0,0,0,0,0]);
assert.ok(temporal.candidates.every(c=>c.evaluationStates.length===0 && c.splitDecision==='not-decided'));
for(const rule of ['volumeBias','absenceBias','reuseBias','selectionBias','conditionBias'])assert.ok(x.biasControls[rule]);
assert.equal(x.biasControls.noAutomaticRank,true);
assert.equal(x.biasControls.noModelWeights,true);
assert.equal(x.biasControls.noPercentWinOdds,true);
assert.equal(x.biasControls.allScoresUnassigned,true);
assert.equal(x.biasControls.confidenceIndependentOfEvidenceCount,true);
assert.equal(pilot.meta.formalEvaluations,0);
assert.equal(pilot.meta.originalCanonScenesVerified,0);
console.log('PASS: all 109 roster L1 *shells*, 3 L2 candidate packs, 1 L3 hypothesis, 0 ratings; fairness and original references verified');
