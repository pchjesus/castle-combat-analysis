import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const get = path => JSON.parse(readFileSync(path,'utf8'));
const data=get('data/research/aquila-domestic-decision-timeline.v2.8.DRAFT.json');
const roster=get('data/roster.v0.1.json');
const pilot=get('data/pilot-evidence.v2.1.json');
const review=get('data/pilot-review-queue.v2.2.json');
assert.equal(data.schemaVersion,'v2.8-aquila-domestic-crosscheck-draft');
assert.equal(data.status,'research-unapproved');
assert.equal(roster.characters.length,109);
assert.equal(roster.organizations.length,17);
assert.equal(roster.characters.find(c=>c.id===data.characterId).name,'아킬라');
assert.equal(roster.characters.find(c=>c.id==='char-042').name,'구스타프');
assert.deepEqual([pilot.battles.length,pilot.evidence.length,pilot.statements.length,review.records.length],[3,12,7,19]);
assert.ok(pilot.battles.every(x=>x.phaseRecords.length===0));
assert.equal(pilot.meta.originalCanonScenesVerified,0);
assert.equal(pilot.meta.formalEvaluations,0);
assert.deepEqual(data.episodes.map(e=>e.episodeId),['AK-G','AK-KHO']);
assert.equal(data.episodes[0].battleCandidate,'pilot-A');
assert.deepEqual(data.episodes[0].existingEvidenceIds,['A01','A02','A03','A04']);
assert.equal(data.episodes[1].battleCandidate,null);
assert.deepEqual(data.episodes[1].existingEvidenceIds,[]);
assert.ok(data.episodes[1].candidateEvidenceId.startsWith('research-only:'));
assert.ok(!pilot.evidence.some(e=>e.id===data.episodes[1].candidateEvidenceId));
for(const ep of data.episodes)assert.equal(ep.originalPanelCheck,'not-done-by-assistant');
assert.equal(data.firsthandUserReports.length,2);
assert.ok(data.firsthandUserReports.every(r=>r.userSaysDirectlyRead===true && r.assistantCheckedOriginalPanel===false && r.exactEpisodeAndPanel===null));
assert.deepEqual(data.firsthandUserReports[0].literalMarkers,['0발','사거리 미달','8/10발']);
assert.equal(data.firsthandUserReports[0].markerAssignment,'not-verified');
assert.equal(data.firsthandUserReports[0].simultaneousDefeat,'not-established');
assert.equal(data.firsthandUserReports[1].verbatimKoreanOriginalCheckedByAssistant,false);
assert.equal(data.sourceCatalog.length,6);
const urls = new Set();
const sources = new Set();
for(const s of data.sourceCatalog) {
 assert.ok(s.url.startsWith('https://'));
 assert.ok(!urls.has(s.url));
 assert.ok(!sources.has(s.id));
 urls.add(s.url); sources.add(s.id);
 assert.equal(s.access,'text-observed');
 assert.ok(s.claims.length>0 && s.limits.length>0);
 assert.ok(s.independenceGroup);
}
assert.equal(data.sourceCatalog.find(s=>s.id==='D05').independenceGroup,data.sourceCatalog.find(s=>s.id==='D06').independenceGroup,'same wiki synthesis not independent');
assert.notEqual(data.sourceCatalog.find(s=>s.id==='D01').independenceGroup,data.sourceCatalog.find(s=>s.id==='D03').independenceGroup);
assert.equal(data.chronologicalDiscriminators.length,6);
assert.equal(data.chronologicalDiscriminators.filter(x=>x.episode==='AK-G').length,4);
assert.equal(data.chronologicalDiscriminators.filter(x=>x.episode==='AK-KHO').length,2);
for(const step of data.chronologicalDiscriminators) assert.ok(step.needsReview.length>=2 && step.epistemic);
assert.deepEqual(data.causalHypotheses.map(m=>m.id),['FAST','ATTRITION','WITHDRAW','LOSS']);
for(const m of data.causalHypotheses) {
 assert.ok(m.hypothesis && m.critique && m.validation);
 for(const id of m.support) assert.ok(sources.has(id) || ['U01','U02'].includes(id));
}
assert.equal(data.causalHypotheses.find(x=>x.id==='ATTRITION').validation,'counterfactual-not-observed');
assert.equal(data.statMapping.length,6);
assert.ok(data.statMapping.every(s=>s.numericScore===null && s.guard));
assert.deepEqual(Object.values(data.approval),[0,0,0,0,0,0]);
assert.ok(data.noEditsTo.every(path=>!path.startsWith('data/research/')));
console.log('PASS: 6 Korean sources, 2 firsthand user reports, 4 competing strategy models, 2 separate battle candidates, no canon/score promotion');
