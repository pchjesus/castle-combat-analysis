import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const get = p => JSON.parse(readFileSync(p, 'utf8'));
const data = get('data/research/l2-axis-attribution.v3.0.DRAFT.json');
const base = get('data/research/analysis-depth-coverage.v2.9.DRAFT.json');
const roster = get('data/roster.v0.1.json');
const pilot = get('data/pilot-evidence.v2.1.json');
const queue = get('data/pilot-review-queue.v2.2.json');
const axes = ['신체 역량','기동','반응','방어','지속전','전술·판단','부동심','상황 대응'];
assert.equal(data.schemaVersion,'v3.0-l2-axis-fairness-experiment-draft');
assert.equal(data.state,'research-only-unapproved');
assert.deepEqual(data.controlledVocabulary.commonAxes,axes);
assert.equal(base.coverageIndex.length,109);
assert.equal(roster.characters.length,109);
assert.equal(roster.organizations.length,17);
assert.deepEqual(data.profiles.map(p=>p.characterId),['char-033','char-087','char-071']);
assert.deepEqual(data.profiles.map(p=>p.existingEvidenceIds.length),[4,4,4]);
assert.deepEqual(data.records.map(e=>e.existingEvidenceId),pilot.evidence.map(e=>e.id));
assert.deepEqual([...new Set(data.records.map(e=>e.existingEvidenceId))].length,12);
assert.deepEqual(queue.records.filter(r=>r.kind==='battleEvidence').map(r=>r.recordId),pilot.evidence.map(e=>e.id));
const sourceIds=new Set(pilot.sourceCatalog.map(s=>s.id));
const battleMap=new Map(pilot.battles.map(b=>[b.id,b]));
const queueMap=new Map(queue.records.map(r=>[r.recordId,r]));
const evidenceMap=new Map(pilot.evidence.map(e=>[e.id,e]));
for (const p of data.profiles) {
  assert.ok(roster.characters.some(c=>c.id===p.characterId));
  assert.equal(p.identityVerifiedBy,'roster-index-only');
  assert.equal(p.sharedTemplate.canonFactCandidateStatus,'secondary-unverified');
  assert.equal(p.sharedTemplate.evaluation.score,null);
  assert.equal(p.sharedTemplate.evaluation.sufficiency,'unassessed');
  assert.equal(p.sharedTemplate.evaluation.approval,'none');
  assert.equal(p.sharedTemplate.calculation.enabled,false);
  assert.equal(p.sharedTemplate.calculation.result,null);
  assert.equal(p.representativeSpecialty.decision,'not-selected');
  const b=battleMap.get(p.battleCandidateIds[0]);
  assert.equal(b.subjectCharacterId,p.characterId);
  assert.deepEqual(p.existingEvidenceIds,pilot.evidence.filter(e=>e.battleId===b.id).map(e=>e.id));
  assert.deepEqual(p.existingReviewIds,p.existingEvidenceIds);
  assert.deepEqual(p.linkedStatementCandidateIds,pilot.statements.filter(e=>e.targetCharacterIds.includes(p.characterId)).map(e=>e.id));
}
for (const r of data.records) {
  const e=evidenceMap.get(r.existingEvidenceId),q=queueMap.get(r.existingReviewId);
  assert.ok(e && q);
  assert.equal(e.id,r.existingReviewId);
  assert.equal(e.battleId,r.battleCandidateId);
  assert.equal(battleMap.get(e.battleId).subjectCharacterId,r.characterId);
  assert.deepEqual(r.sourceIds,e.sourceIds);
  assert.equal(r.sourceVerification,e.sourceVerification);
  assert.ok(r.sourceIds.every(id=>sourceIds.has(id)));
  assert.equal(e.sceneCanonVerified,false);
  assert.equal(q.verification,'not-directly-checked');
  assert.equal(q.approval,'none');
  assert.equal(r.verification.assistantOriginalChecked,false);
  assert.equal(r.verification.userOriginalObservationLinkedToThisSpecificRecord,false);
  assert.equal(r.canonFact.confirmed,false);
  assert.equal(r.canonFact.observedAction,null);
  assert.equal(r.combatContext.sceneCheckRequired,true);
  assert.ok(r.interpretation.candidate && r.interpretation.competing && r.interpretation.reviewGate);
  assert.ok(r.attribution.exclusiveOutcomeCluster);
  assert.equal(r.attribution.secondaryDoesNotCountAsIndependent,true);
  assert.equal(r.attribution.readyToScore,false);
  assert.equal(r.evaluation.approval,'none');
  assert.equal(r.evaluation.sufficiency,'unassessed');
  assert.equal(r.evaluation.specialty.score,null);
  assert.equal(r.evaluation.specialty.domain,null);
  assert.equal(r.evaluation.specialty.usageStatus,'unassessed');
  assert.deepEqual(Object.keys(r.evaluation.commonAxes),axes);
  assert.ok(Object.values(r.evaluation.commonAxes).every(v=>v.score===null && v.assessment==='unassessed'));
  assert.equal(r.calculation.enabled,false);
  assert.equal(r.calculation.result,null);
  assert.ok(!r.attribution.conditionalSecondary.some(x=>x.lane===r.attribution.primaryCandidate.lane && x.name===r.attribution.primaryCandidate.name));
  if(r.attribution.primaryCandidate.lane==='common-axis')assert.ok(axes.includes(r.attribution.primaryCandidate.name));
  if(r.attribution.primaryCandidate.lane==='specialty')assert.ok(data.controlledVocabulary.specialistDomains.includes(r.attribution.primaryCandidate.name));
  if(r.attribution.primaryCandidate.lane==='combat-context')assert.equal(r.attribution.primaryCandidate.name,null);
}
assert.equal(data.records.find(r=>r.existingEvidenceId==='R04').attribution.primaryCandidate.lane,'combat-context');
assert.ok(data.userOriginalObservationMemo.some(x=>x.eventCandidate==='AK-KHO' && x.mergedIntoPilotA===false && !x.assistantChecked));
assert.ok(data.userOriginalObservationMemo.every(x=>!x.assistantChecked));
assert.equal(data.controlledVocabulary.nonScoredLenses.includes('심리전'),true);
assert.equal(data.controlledVocabulary.commonAxes.includes('심리전'),false);
assert.ok(data.scoringPolicy.allScoresNull && data.scoringPolicy.sufficiencyIndependent && !data.scoringPolicy.scoreFromDocumentCount);
assert.equal(data.scoringPolicy.modelWeights,null);
assert.equal(data.scoringPolicy.winProbabilities,null);
assert.equal(data.scoringPolicy.ranking,null);
assert.deepEqual(data.biasAudit.rawEvidencePerPilot,[4,4,4]);
assert.deepEqual(Object.values(data.approval).slice(0,3),[0,0,0]);
assert.ok(pilot.evidence.every(x=>x.scoreImpact==='none'));
assert.equal(pilot.meta.formalEvaluations,0);
assert.equal(pilot.meta.originalCanonScenesVerified,0);
// Counterfactual fairness: adding duplicate source mentions must not alter any evaluation.
const duplicateCopy=structuredClone(data);
duplicateCopy.records[0].sourceIds.push(duplicateCopy.records[0].sourceIds[0]);
const ratings=x=>x.records.map(r=>JSON.stringify(r.evaluation));
assert.deepEqual(ratings(duplicateCopy),ratings(data),'secondary source duplication changes no scores');
const blankAxis=data.records.find(r=>r.existingEvidenceId==='L03').evaluation.commonAxes['부동심'];
assert.deepEqual(blankAxis,{score:null,assessment:'unassessed'},'unobserved is not zero');
console.log('PASS: v3.0 L2 109/17 preserved, 12 linked candidates, 8+1 non-scoring lanes, no source inflation, original verification gate');
