import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const get=p=>JSON.parse(readFileSync(p,'utf8'));
const roster=get('data/roster.v0.1.json');
const previous=get('data/research/quotation-shortlist.v3.3.DRAFT.json');
const user=get('data/research/user-quotation-curation.v3.3.DRAFT.json');
const official=get('data/quotation-review.v0.1.json');
const policy=get('data/research/quotation-intake-policy.v3.2.DRAFT.json');
assert.equal(roster.characters.length,109);
assert.deepEqual(official.quotationCandidates,[]);
assert.equal(policy.publication.approvedQuoteCount,0);
assert.equal(previous.candidates.length,10);
assert.equal(user.schemaVersion,'v3.3-user-quotation-curation-draft');
assert.equal(user.userInput.count,9);
assert.equal(user.crosswalk.length,9);
assert.equal(user.userInput.selectedCharacterId,'char-033');
assert.equal(user.userInput.selectedCandidateId,'CQ-012');
assert.equal(user.userInput.exactWordingProvidedInConversation,true);
assert.equal(user.userInput.exactWordingStoredInPublicRepo,false);
assert.equal(user.userInput.userExplicitlyConfirmedReadingTheseExactNineDuringSubmission,false);
assert.equal(user.guard.publishedCount,0);
assert.equal(user.guard.scoreAssignmentBlocked,true);
const existing=new Map(previous.candidates.map(x=>[x.candidateId,x]));
assert.deepEqual(user.existingCandidateIdsPreserved,[...existing.keys()]);
const added=new Map(user.newDistinctCandidates.map(x=>[x.candidateId,x]));
assert.deepEqual([...added.keys()],['CQ-011','CQ-012','CQ-013']);
assert.equal(added.get('CQ-011').priorShortlistItem,'CQ-005');
assert.equal(added.get('CQ-012').priorShortlistItem,'CQ-007');
assert.equal(added.get('CQ-013').priorShortlistItem,'CQ-010');
const ids=new Set();
const speakers=new Set();
for(const item of user.crosswalk){
 assert.ok(!ids.has(item.candidateId));ids.add(item.candidateId);
 assert.ok(roster.characters.some(x=>x.id===item.characterId&&x.name===item.characterName));
 assert.ok(!speakers.has(item.characterId));speakers.add(item.characterId);
 assert.ok(existing.has(item.candidateId)||added.has(item.candidateId));
 if(existing.has(item.candidateId))assert.equal(item.characterId,existing.get(item.candidateId).characterId);
 if(added.has(item.candidateId))assert.equal(item.characterId,added.get(item.candidateId).characterId);
 assert.equal(item.exactText,null,'No copyrighted/user supplied comic dialogue in public branch');
 assert.equal(item.sourceVerification,'user-provided-transcription-not-rechecked-in-canon');
 assert.equal(item.speakerCanonVerified,false);
 assert.equal(item.independentlyChecked,false);
 assert.equal(item.scenePart,null);
 assert.equal(item.sceneEpisode,null);
 assert.equal(item.publishClearance,'pending');
 assert.equal(item.combatScoringImpact,'none');
 assert.ok(item.motifParaphrase.length>10);
}
assert.equal(speakers.size,9);
const first=user.crosswalk.filter(x=>x.rank===1);
assert.equal(first.length,1);
assert.deepEqual(first.map(x=>x.candidateId),['CQ-012']);
assert.equal(user.crosswalk.find(x=>x.candidateId==='CQ-012').editorialPriority,'first-choice');
for(const item of user.newDistinctCandidates){
 assert.equal(item.exactText,null);
 assert.equal(item.originalCheckedByAssistant,false);
 assert.equal(item.originalCheckedByUser,'not-confirmed-as-contemporaneous-check');
 assert.equal(item.quotationPublicationCleared,false);
}
console.log('PASS: nine user quote nominations, Aquila priority, distinct IDs, no public verbatim quotes, no score/publication changes');
