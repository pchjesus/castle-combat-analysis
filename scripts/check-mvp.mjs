import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const roster = JSON.parse(readFileSync('data/roster.v0.1.json', 'utf8'));
const html = readFileSync('index.html', 'utf8');
const embedded = html.match(/<script type="application\/json" id="roster-payload">([\s\S]*?)<\/script>/);
assert.ok(embedded, 'embedded roster missing');
const siteRoster = JSON.parse(embedded[1]);
assert.deepEqual(siteRoster, roster, 'site roster differs from canonical registry');
assert.equal(roster.characters.length, 109);
assert.equal(roster.organizations.length, 17);
assert.equal(roster.schemaVersion, '0.1');
assert.deepEqual(roster.characters.map(c => c.id),Array.from({length:109},(_,i)=>'char-'+String(i+1).padStart(3,'0')));
assert.equal(new Set(roster.characters.map(c=>c.name)).size,109);
assert.ok(roster.characters.every(c => c.status==='candidate'));
const orgs = new Map(roster.organizations.map(o=>[o.id,o]));
assert.ok(roster.characters.every(c=>orgs.has(c.initialOrganizationId)));
for (const org of roster.organizations) assert.equal(roster.characters.filter(c=>c.initialOrganizationId===org.id).length,org.initialRosterCount);
for(const [name,id] of Object.entries({'아킬라':'char-033','리천':'char-087','류지학':'char-071'})) assert.equal(roster.characters.find(c=>c.id===id)?.name, name);
assert.match(html,/비공식 · 비영리 팬 제작 프로젝트/);
assert.match(html,/원작 직접 대조/);
assert.match(html,/M1 보류/);
assert.match(html,/M2 보류/);
assert.doesNotMatch(html,/<img\b/i,'no copyrighted character images are approved for this release');
assert.ok(html.includes('미평가'));
console.log('PASS: 109/17 roster, IDs, refs, no scores/images, fan notice and M0 guard');
